-- Типичные услуги для самозаписи, чтобы пациент выбирал не только консультацию.
-- Длительность — ориентир: врач меняет её или скрывает услугу в «Меню → Услуги для самозаписи».
-- Если врач уже завёл услугу с таким же именем, она не дублируется.
insert into service_type (name, duration_minutes)
select v.name, v.duration_minutes
from (values
    ('Лечение кариеса', 60),
    ('Профессиональная чистка', 60),
    ('Удаление зуба', 45),
    ('Лечение каналов', 90),
    ('Консультация по брекетам', 30),
    ('Осмотр и коррекция брекетов', 30),
    ('Отбеливание', 90)
) as v (name, duration_minutes)
where not exists (select 1 from service_type s where lower(s.name) = lower(v.name));
